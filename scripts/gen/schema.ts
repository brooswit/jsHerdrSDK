import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export type JSONSchema = Record<string, any>;

const here = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(here, "..", "..");
export const SCHEMA_PATH = join(ROOT, "schema", "herdr-api.schema.json");
export const OUT_DIR = join(ROOT, "src", "generated");

export async function loadSchema(): Promise<JSONSchema> {
  return JSON.parse(await Bun.file(SCHEMA_PATH).text());
}

export function header(schema: JSONSchema): string {
  return `// GENERATED by scripts/gen from schema/herdr-api.schema.json — do not edit.\n// herdr protocol ${schema.protocol}, schema_version ${schema.schema_version}.\n`;
}
